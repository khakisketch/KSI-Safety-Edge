package ksi.rc

import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.node.ObjectNode

/** Envelope-level protocol failure (mirrors Python `EnvelopeError`). */
class MopError(message: String) : IllegalArgumentException(message)

/**
 * MOP (Mission-Oriented Protocol) envelope + constants.
 *
 * Ported from the validated harness implementation
 * (`harness/src/ksi_harness/mop.py`): channel/message-type sets, the
 * `ksi-safety-edge-harness` UUID namespace, `new_msg_id` derivation, and
 * the envelope shape with `payload_sha256` over RFC 8785 canonical bytes.
 * `MopContractTest` pins golden values generated by the Python module so
 * both sides produce identical ids and digests.
 */
object Mop {
    const val PROTOCOL_VERSION = 1

    val NAMESPACE: java.util.UUID =
        Uuid5.of(Uuid5.DNS_NAMESPACE, "ksi-safety-edge-harness")

    val CHANNELS = setOf(
        "CONTROL_RELIABLE", "EVENT_RELIABLE", "EVIDENCE_TRANSFER", "HEARTBEAT",
    )
    val DATA_CHANNELS = setOf("EVENT_RELIABLE", "EVIDENCE_TRANSFER")

    val RC_TO_EDGE = setOf(
        "MISSION_PREPARE", "MISSION_APPLY", "MISSION_STATUS_QUERY",
        "SESSION_START", "SESSION_STOP",
    )
    val EDGE_TO_RC = setOf(
        "MISSION_PREPARED", "MISSION_APPLY_REJECTED", "MISSION_APPLIED",
        "MISSION_STATUS", "OBSERVATION", "DETECTION_EVENT", "FLIGHT_SUMMARY",
        "ARTIFACT_ANNOUNCE", "ARTIFACT_CHUNK", "HEARTBEAT", "ACK",
    )

    /** Control-plane messages handled by the mission controller. */
    val CONTROL_MESSAGE_TYPES = setOf(
        "MISSION_PREPARED", "MISSION_APPLY_REJECTED", "MISSION_APPLIED",
        "MISSION_STATUS",
    )

    /** Evidence-plane messages handled by the evidence ingest. */
    val DATA_MESSAGE_TYPES = setOf(
        "OBSERVATION", "DETECTION_EVENT", "FLIGHT_SUMMARY",
        "ARTIFACT_ANNOUNCE", "ARTIFACT_CHUNK", "HEARTBEAT",
    )

    private val mapper = ObjectMapper()

    /** Public mapper for payload construction (shared JSON semantics). */
    val json: ObjectMapper get() = mapper

    fun newMsgId(vararg parts: String): String =
        Uuid5.of(NAMESPACE, parts.joinToString("|")).toString()

    fun makeEnvelope(
        msgId: String,
        channel: String,
        type: String,
        flightId: String,
        edgeBootId: String?,
        seq: Int?,
        ackOf: String?,
        payload: ObjectNode,
        sentMonotonicNs: Long,
    ): ObjectNode {
        if (channel !in CHANNELS) throw MopError("unknown channel $channel")
        val env = mapper.createObjectNode()
        env.put("protocol_version", PROTOCOL_VERSION)
        env.put("msg_id", msgId)
        env.put("channel", channel)
        env.put("type", type)
        env.put("flight_id", flightId)
        env.putOrNull("edge_boot_id", edgeBootId)
        env.putOrNull("seq", seq)
        env.putOrNull("ack_of", ackOf)
        env.set<JsonNode>("payload", payload)
        env.put("payload_sha256", CanonicalJson.digestSha256(payload))
        env.put("sent_monotonic_ns", sentMonotonicNs)
        // Fail fast on non-serializable envelopes (mirrors json.dumps).
        mapper.writeValueAsString(env)
        return env
    }

    /** JSON round-trip + digest verify; returns (envelope, payload). */
    fun verifyEnvelope(rawJson: String): Pair<ObjectNode, ObjectNode> {
        val env = try {
            mapper.readTree(rawJson) as? ObjectNode
        } catch (exc: Exception) {
            throw MopError("envelope not JSON: ${exc.message}")
        } ?: throw MopError("envelope must be an object")
        if (env.get("protocol_version")?.asInt() != PROTOCOL_VERSION) {
            throw MopError("bad protocol_version")
        }
        val payload = env.get("payload")
        if (payload == null || !payload.isObject) {
            throw MopError("payload must be an object")
        }
        if (CanonicalJson.digestSha256(payload) !=
            env.get("payload_sha256")?.asText()
        ) {
            throw MopError("payload_sha256 mismatch")
        }
        return env to payload as ObjectNode
    }
}

private fun ObjectNode.putOrNull(field: String, value: String?) {
    if (value == null) putNull(field) else put(field, value)
}

private fun ObjectNode.putOrNull(field: String, value: Int?) {
    if (value == null) putNull(field) else put(field, value)
}
