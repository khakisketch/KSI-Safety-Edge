package ksi.rc

import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.node.ObjectNode
import java.security.MessageDigest
import org.erdtman.jcs.JsonCanonicalizer

/**
 * Canonical JSON digests (RFC 8785 / JCS), byte-for-byte compatible with
 * the Python `ksi_contracts` module (`libs/ksi_contracts/.../canonical.py`):
 * digest fields are the hex SHA256 of the canonical bytes of the object
 * excluding the digest field itself.
 *
 * Uses the reference Java JCS implementation so float/number formatting
 * (the known cross-language gap, audit F9) stays identical to Python's
 * `rfc8785` output; `MopContractTest` pins golden values generated by the
 * actual Python module.
 */
object CanonicalJson {
    fun canonicalBytes(value: JsonNode): ByteArray =
        JsonCanonicalizer(value.toString()).encodedUTF8

    fun digestSha256(value: JsonNode): String {
        val md = MessageDigest.getInstance("SHA-256")
        return md.digest(canonicalBytes(value)).joinToString("") {
            (it.toInt() and 0xFF).toString(16).padStart(2, '0')
        }
    }

    /** Digest of a copy of [obj] without [field] (shallow, like Python). */
    fun digestExcluding(obj: ObjectNode, field: String): String {
        val copy = obj.deepCopy()
        copy.remove(field)
        return digestSha256(copy)
    }

    /** True when `obj[field]` equals the digest excluding `field`. */
    fun verifyDigest(obj: JsonNode, field: String): Boolean {
        if (!obj.isObject) return false
        val claimed = obj.get(field)
        if (claimed == null || !claimed.isTextual) return false
        return try {
            digestExcluding(obj as ObjectNode, field) == claimed.asText()
        } catch (_: Exception) {
            false
        }
    }
}
