#!/usr/bin/env python3
"""make_replay_frames.py — build a replay manifest + raw RGB frames from images.

Host helper for the R1 Replay driver (edge/tools/replay_run). Converts each
input image (any PIL-readable format) to raw RGB (width*height*3 bytes, no
header) and writes a ksi replay manifest v1 with one frame per image.

usage: make_replay_frames.py --out-dir DIR [--manifest PATH] [--fps F]
       [--start-ns N] [--pose-hz F] IMAGE [IMAGE ...]

- Frames are spaced 1/fps seconds apart starting at --start-ns (default 1e9).
- --pose-hz adds SYNTHETIC attitude samples (identity quaternion) at that
  rate across the frame window, with a verify line for the replay_fc device
  domain. Synthetic telemetry exists for pipeline plumbing tests (R1/R3); it
  makes no capture-time claim and is never product evidence.
- Requires Pillow. Host-only helper; the product never depends on it.
"""

import argparse
import os

from PIL import Image


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--manifest", default=None)
    parser.add_argument("--fps", type=float, default=15.0)
    parser.add_argument("--start-ns", type=int, default=1_000_000_000)
    parser.add_argument("--pose-hz", type=float, default=0.0)
    parser.add_argument("images", nargs="+")
    args = parser.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    manifest_path = args.manifest or os.path.join(args.out_dir, "manifest.txt")
    step_ns = int(round(1e9 / args.fps))

    lines = [
        "# ksi-safety replay manifest v1 (generated by make_replay_frames.py)",
        "verify host_mono host_receive replay_harness_clock",
    ]

    frame_records = []
    for index, image_path in enumerate(args.images):
        image = Image.open(image_path).convert("RGB")
        width, height = image.size
        relative = f"f{index + 1:04d}.rgb"
        with open(os.path.join(args.out_dir, relative), "wb") as handle:
            handle.write(image.tobytes())  # tightly packed RGB, w*h*3 bytes
        recv_ns = args.start_ns + index * step_ns
        lines.append(f"frame {index + 1} {recv_ns} {width} {height} {relative}")
        frame_records.append(recv_ns)

    if args.pose_hz > 0 and frame_records:
        lines.append("verify replay_fc device_sensor replay_fc_sim")
        pose_step_ns = int(round(1e9 / args.pose_hz))
        sample_id = 0
        t = frame_records[0]
        while t <= frame_records[-1]:
            sample_id += 1
            # Synthetic identity attitude; source time = receive time in the
            # synthetic replay_fc domain (simulated clock, clearly labelled).
            lines.append(f"pose {sample_id} {sample_id} {t} replay_fc {t} 1 0 0 0")
            t += pose_step_ns

    with open(manifest_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {len(args.images)} frames + manifest: {manifest_path}")


if __name__ == "__main__":
    main()
